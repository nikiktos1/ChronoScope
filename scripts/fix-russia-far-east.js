// Функция поиска России в карте
function findRussia(features) {
  return features.find(f => {
    const name = f.properties.name.toLowerCase();
    return name.includes('росс') || name.includes('russian') || 
           name.includes('soviet') || name.includes('ссср') ||
           name.includes('московск');
  });
}

// Обрабатываем каждую карту
maps.forEach(mapFile => {
  const filePath = `public/data/maps/${mapFile}`;
  
  try {
    const data = JSON.parse(fs.readFileSync(filePath, 'utf8'));
    const russia = findRussia(data.features);
    
    if (russia) {
      console.log(`📍 Найдена Россия в ${mapFile}: "${russia.properties.name}"`);
      
      // Обновляем геометрию России
      russia.geometry = fullRussianGeometry;
      
      // Сохраняем обновленную карту
      fs.writeFileSync(filePath, JSON.stringify(data, null, 2));
      console.log(`✅ Обновлена геометрия России в ${mapFile}`);
    } else {
      console.log(`⚠️  Россия не найдена в ${mapFile}`);
    }
  } catch (error) {
    console.log(`❌ Ошибка обработки ${mapFile}:`, error.message);
  }
});

